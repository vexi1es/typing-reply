import basicSsl from '@vitejs/plugin-basic-ssl';
import { createHash } from 'node:crypto';
import { readdirSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import type { Plugin } from 'vite';
import { defineConfig } from 'vitest/config';

/** All files in public/ as site paths ("/favicon.svg", …). */
function publicFiles(dir = 'public'): string[] {
  const out: string[] = [];
  const walk = (d: string) => {
    for (const name of readdirSync(d)) {
      const p = join(d, name);
      if (statSync(p).isDirectory()) walk(p);
      else if (!name.startsWith('_')) out.push('/' + relative(dir, p).replaceAll('\\', '/'));
    }
  };
  walk(dir);
  return out;
}

/**
 * Offline support: emits sw.js that precaches the whole build (page, JS chunks including the lazy
 * video module, fonts, icons). The cache name is a hash of the file list, so every new build
 * replaces the old cache.
 */
function serviceWorker(): Plugin {
  return {
    name: 'offline-sw',
    apply: 'build',
    generateBundle(_, bundle) {
      const files = ['/', ...Object.keys(bundle).map((f) => '/' + f), ...publicFiles()].filter(
        (f) => f !== '/index.html',
      );
      // The version covers both the file list and the worker's own code.
      const version = createHash('sha1').update(swSource('', files)).digest('hex').slice(0, 10);
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: swSource(version, files) });
    },
  };
}

const swSource = (version: string, files: string[]) => `// Generated by vite.config.ts
const CACHE = 'pjt-${version}';
const FILES = ${JSON.stringify(files)};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  if (req.mode === 'navigate') {
    // The page: fresh from the network when online (so updates show up at once),
    // the cached copy when offline or the network is too slow.
    e.respondWith(
      Promise.race([
        fetch(req).then((res) => {
          if (!res.ok) throw new Error(res.status);
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put('/', copy));
          return res;
        }),
        new Promise((_, reject) => setTimeout(() => reject(new Error('timeout')), 2500)),
      ]).catch(() => caches.match('/', { ignoreVary: true })),
    );
    return;
  }
  // Everything else: cache first — file names carry content hashes.
  // ignoreVary: servers add “Vary: Origin”, and module scripts are requested with an Origin header
  // while the precache requests had none — without it nothing would match offline.
  e.respondWith(caches.match(req, { ignoreSearch: true, ignoreVary: true }).then((hit) => hit || fetch(req)));
});
`;

// HTTPS=1 npm run dev — self-signed certificate to open the site from a phone over LAN.
export default defineConfig({
  plugins: [serviceWorker(), ...(process.env.HTTPS ? [basicSsl()] : [])],
  build: {
    target: 'es2022',
  },
  test: {
    include: ['src/**/*.test.ts'],
  },
});
